test("yaac: a turn that is a mesh delivery is a notice from YAAC, not a user message", () => {
  const framed = frameMessages([{ id: "m1", kind: "message", from: "addr:1", fromLabel: "Builder · Codex", text: "[Task from me]\nreview the PR", task: true }]);
  const item = userItem({ id: "user:1", turnId: "1" }, [textPart(framed)], CLAUDE_MARKUP);
  assert.equal(item.kind, "notice");
  assert.equal((item as { text: string }).text, "Task from Builder · Codex · via YAAC");
  assert.equal((item as { body: string }).body, "Task from Builder · Codex:\n[Task from me]\nreview the PR");
  const two = frameMessages(
    [
      { id: "m2", kind: "message", from: "a", fromLabel: "A", text: "hi" },
      { id: "m3", kind: "result", from: "b", fromLabel: "B", text: "done" },
    ],
    "You are thread X.",
  );
  const f = meshFrames(two)!;
  assert.equal(f.text, "2 agent messages · via YAAC");
  assert.match(f.body, /^YAAC introduction:\nYou are thread X\.\n\nMessage from A:\nhi\n\nResult from B:\ndone$/);
  assert.equal(meshFrames("[Task from me] typed by a person"), null);
});

test("yaac: the handoff preamble is a context part; the user's text follows; the fork transcript leaves it out", () => {
  const text = `${preamble("/state/t.md", { target: "devbox", threadId: "th_1" }, false)}continue the refactor`;
  const item = userItem({ id: "user:2", turnId: "2" }, [textPart(text)], CODEX_MARKUP);
  const parts = (item as { parts: InputPart[] }).parts;
  assert.equal(parts.length, 2);
  assert.equal((parts[0] as { role?: string; label?: string }).role, "context");
  assert.equal((parts[0] as { label?: string }).label, "YAAC handoff note");
  assert.deepEqual(parts[1], T("continue the refactor"));
  const md = renderTranscript([item, { ...(promptItem("u3", "3", '<pasted_content id="1">\nlog\n</pasted_content id="1">\nwhy', { kind: "human" }) as Item) }], { title: "t", provider: "p", target: "x", threadId: "th" }, { upload: () => null, exists: () => true });
  assert.doesNotMatch(md.markdown, /YAAC handoff|pasted_content/);
  assert.match(md.markdown, /continue the refactor/);
  assert.match(md.markdown, /log\n\nwhy/);
});

