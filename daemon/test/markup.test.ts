test("claude: several task ids, an internal marker, status stopped, a note: one notice without the marker", () => {
  const text = notification(
    "<task-id>bk1</task-id>\n<task-id>bk2</task-id>\n<task-id>__orphan_summary__:shell</task-id>\n<status>stopped</status>\n<summary>2 background shell command tasks didn't finish before the previous session ended.</summary>\n<note>They were stopped.\nRun them again if needed.</note>",
  );
  const n = taskNotice(text)!;
  assert.equal(n.text, "2 background shell command tasks didn't finish before the previous session ended.");
  assert.equal(n.body, "2 background shell command tasks didn't finish before the previous session ended.\n\nThey were stopped.\nRun them again if needed.");
  assert.deepEqual(n.details, { tasks: [{ taskIds: ["bk1", "bk2"], status: "stopped" }] });
  for (const status of ["failed", "killed", "blocked"]) {
    assert.equal(taskNotice(notification(`<task-id>x</task-id>\n<status>${status}</status>`))!.text, `Background task ${status}`);
  }
  assert.equal(taskNotice(notification("<task-id>x</task-id>"))!.text, "Background task update");
});

