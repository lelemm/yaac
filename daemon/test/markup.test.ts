const notification = (inner: string) => `<task-notification>\n${inner}\n</task-notification>`;

test("claude: a background command notification: the summary is the line, no tags anywhere", () => {
  const text = notification(
    '<task-id>b3kx</task-id>\n<tool-use-id>toolu_01</tool-use-id>\n<output-file>/tmp/tasks/b3kx.output</output-file>\n<status>completed</status>\n<summary>Background command "grep -oE &quot;a&lt;b&quot;" completed (exit code 0)</summary>',
  );
  const item = promptItem("n1", "n1", text, { kind: "task-notification", producer: "session-task" });
  assert.equal(item.kind, "notice");
  assert.equal((item as { text: string }).text, 'Background command "grep -oE "a<b"" completed (exit code 0)');
  const body = (item as { body: string }).body;
  assert.match(body, /Output: \/tmp\/tasks\/b3kx\.output/);
  assert.doesNotMatch(body, /<\/?(task|status|summary|output)/);
});

