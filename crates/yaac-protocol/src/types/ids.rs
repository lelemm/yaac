/// A data stream number, used by `0x02` data frames. Allocated by the side that will receive
/// the stream (for uploads: `yaacd`, in `upload/begin`).
#[derive(
    Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, JsonSchema,
)]
#[serde(transparent)]
pub struct StreamId(pub u32);

impl fmt::Display for StreamId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.0.fmt(f)
    }
}

/// A journal epoch: one continuous journal. Changes only when a journal is started afresh.
#[derive(
    Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Default, Serialize, Deserialize, JsonSchema,
)]
#[serde(transparent)]
pub struct Epoch(pub u64);

/// A sequence number within an epoch. Increases by one per event and is never reused.
#[derive(
    Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Default, Serialize, Deserialize, JsonSchema,
)]
#[serde(transparent)]
pub struct Seq(pub u64);

/// A position in a thread's journal.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize, JsonSchema)]
pub struct JournalPosition {
    /// The journal.
    pub epoch: Epoch,
    /// The last event included.
    pub seq: Seq,
}

impl JournalPosition {
    /// Whether an event at `(epoch, seq)` lies strictly after this position, i.e. must be
    /// applied. Events at or before it are already contained in the snapshot.
    pub fn admits(&self, epoch: Epoch, seq: Seq) -> bool {
        epoch == self.epoch && seq > self.seq
    }
}

/// The address of an agent: a thread on a target.
///
/// On the wire this is an **opaque string**. Agents never construct one; they get it from a
/// tool result, a received message, or the user. Its three immutable parts are the target id
/// (not the renamable target name), the provider instance with its store binding, and the
/// native thread id; the last two are what [`ThreadId`] encodes. The format is
/// `<target id>/<thread id>`; a target id never contains `/`. Decoding never fails: a string
/// that does not have that shape is kept and simply has no parts.
#[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize, JsonSchema)]
#[serde(transparent)]
pub struct Address(pub String);

impl Address {
    /// Builds the address of `thread` on `target`.
    pub fn new(target: &TargetId, thread: &ThreadId) -> Self {
        Self(format!("{}/{}", target.as_str(), thread.as_str()))
    }

    /// The wire string.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// The target part, when the address has the expected shape.
    pub fn target(&self) -> Option<TargetId> {
        self.split().map(|(target, _)| TargetId::new(target))
    }

    /// The thread part, when the address has the expected shape.
    pub fn thread(&self) -> Option<ThreadId> {
        self.split().map(|(_, thread)| ThreadId::new(thread))
    }

    fn split(&self) -> Option<(&str, &str)> {
        let (target, thread) = self.0.split_once('/')?;
        (!target.is_empty() && !thread.is_empty()).then_some((target, thread))
    }
}

impl fmt::Display for Address {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}
