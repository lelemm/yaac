//! JSON Schema (the subset `current_schema` produces) → TypeScript.
//!
//! * An object definition with only properties becomes an `interface`; anything else a
//!   `type` alias. Properties not in `required` are optional (`name?:`).
//! * `anyOf`/`oneOf` become unions, `allOf` and "object with properties plus a union" (a
//!   flattened field) become intersections.
//! * Members marked `x-yaac-unknown` are left out of unions: they stand for values a newer
//!   peer may send. Such types say so in their doc comment; code must still accept and keep
//!   values outside the union at run time.

use std::fmt::Write as _;

use serde_json::{Map, Value};

const HEADER: &str = "// Generated by `cargo run -p yaac-protocol --bin yaac-protocol-gen` from the Rust types in\n// crates/yaac-protocol. Do not edit: change the Rust types and regenerate.\n";

const OPEN_NOTE: &str = "Open: a newer peer may send values not listed here. Keep them and treat them as unknown; never reject them.";

/// Generates `(file name, contents)` for every TypeScript file.
pub(super) fn generate(schema: &Value, schema_hash: &str) -> Vec<(&'static str, String)> {
    vec![
        ("types.ts", types_file(schema)),
        ("constants.ts", constants_file(schema, schema_hash)),
        ("index.ts", format!("{HEADER}\nexport * from \"./types.js\";\nexport * from \"./constants.js\";\n")),
    ]
}

fn types_file(schema: &Value) -> String {
    let mut out = String::from(HEADER);
    out.push_str("//\n// Every wire type of the YAAC protocol. Field names are as on the wire.\n");
    let empty = Map::new();
    let defs = schema.get("$defs").and_then(Value::as_object).unwrap_or(&empty);
    for (name, def) in defs {
        out.push('\n');
        let open = is_open(def);
        doc_comment(&mut out, def.get("description").and_then(Value::as_str), open, "");
        if is_plain_object(def) {
            let _ = writeln!(out, "export interface {name} {}", object_body(def, ""));
        } else {
            let _ = writeln!(out, "export type {name} = {};", expr(def, ""));
        }
    }
    out
}

fn is_open(schema: &Value) -> bool {
    ["anyOf", "oneOf"].iter().any(|key| {
        schema.get(*key).and_then(Value::as_array).is_some_and(|members| members.iter().any(is_unknown))
    })
}

fn is_unknown(schema: &Value) -> bool {
    schema.get("x-yaac-unknown").and_then(Value::as_bool) == Some(true)
}

fn is_plain_object(schema: &Value) -> bool {
    schema.get("type").and_then(Value::as_str) == Some("object")
        && schema.get("properties").is_some()
        && schema.get("additionalProperties").is_none()
        && !["anyOf", "oneOf", "allOf"].iter().any(|k| schema.get(*k).is_some())
}

fn doc_comment(out: &mut String, text: Option<&str>, open: bool, indent: &str) {
    let mut lines: Vec<String> = text.map(|t| t.lines().map(str::to_owned).collect()).unwrap_or_default();
    if open {
        if !lines.is_empty() {
            lines.push(String::new());
        }
        lines.push(OPEN_NOTE.to_owned());
    }
    if lines.is_empty() {
        return;
    }
    let _ = writeln!(out, "{indent}/**");
    for line in lines {
        let line = line.replace("*/", "*\\/");
        if line.is_empty() {
            let _ = writeln!(out, "{indent} *");
        } else {
            let _ = writeln!(out, "{indent} * {line}");
        }
    }
    let _ = writeln!(out, "{indent} */");
}

fn ident_or_quoted(name: &str) -> String {
    let valid = name.chars().next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if valid { name.to_owned() } else { serde_json::to_string(name).unwrap_or_default() }
}

fn ref_name(reference: &str) -> String {
    reference.rsplit('/').next().unwrap_or(reference).to_owned()
}

fn object_body(schema: &Value, indent: &str) -> String {
    let inner = format!("{indent}  ");
    let empty = Map::new();
    let props = schema.get("properties").and_then(Value::as_object).unwrap_or(&empty);
    let required: Vec<&str> =
        schema.get("required").and_then(Value::as_array).map(|r| r.iter().filter_map(Value::as_str).collect()).unwrap_or_default();
    let mut out = String::from("{\n");
    for (name, prop) in props {
        doc_comment(&mut out, prop.get("description").and_then(Value::as_str), false, &inner);
        let optional = if required.contains(&name.as_str()) { "" } else { "?" };
        let _ = writeln!(out, "{inner}{}{optional}: {};", ident_or_quoted(name), expr(prop, &inner));
    }
    if let Some(additional) = schema.get("additionalProperties")
        && additional != &Value::Bool(false)
    {
        let _ = writeln!(out, "{inner}[key: string]: {};", expr(additional, &inner));
    }
    let _ = write!(out, "{indent}}}");
    out
}

fn union(parts: Vec<String>) -> String {
    let mut unique: Vec<String> = Vec::new();
    for part in parts {
        if !unique.contains(&part) {
            unique.push(part);
        }
    }
    match unique.len() {
        0 => "never".to_owned(),
        1 => unique.remove(0),
        _ => unique.iter().map(|p| paren(p)).collect::<Vec<_>>().join(" | "),
    }
}

fn paren(part: &str) -> String {
    if part.contains(" | ") || part.contains(" & ") { format!("({part})") } else { part.to_owned() }
}

/// The TypeScript type expression for a schema.
fn expr(schema: &Value, indent: &str) -> String {
    let Value::Object(map) = schema else {
        return if schema == &Value::Bool(false) { "never".to_owned() } else { "unknown".to_owned() };
    };
    if let Some(Value::String(reference)) = map.get("$ref") {
        return ref_name(reference);
    }
    if let Some(constant) = map.get("const") {
        return serde_json::to_string(constant).unwrap_or_default();
    }
    if let Some(Value::Array(values)) = map.get("enum") {
        return union(values.iter().map(|v| serde_json::to_string(v).unwrap_or_default()).collect());
    }
    // A union, possibly next to an object part (a flattened field).
    let mut intersection: Vec<String> = Vec::new();
    if let Some(Value::Array(members)) = map.get("allOf") {
        intersection.extend(members.iter().map(|m| expr(m, indent)));
    }
    for key in ["anyOf", "oneOf"] {
        if let Some(Value::Array(members)) = map.get(key) {
            let parts: Vec<String> = members.iter().filter(|m| !is_unknown(m)).map(|m| expr(m, indent)).collect();
            intersection.push(union(parts));
        }
    }
    let base = type_expr(map, indent);
    if !intersection.is_empty() {
        if let Some(base) = base
            && base != "{ [key: string]: unknown }"
        {
            intersection.insert(0, base);
        }
        return if intersection.len() == 1 {
            intersection.remove(0)
        } else {
            intersection.iter().map(|p| paren(p)).collect::<Vec<_>>().join(" & ")
        };
    }
    base.unwrap_or_else(|| "unknown".to_owned())
}

fn type_expr(map: &Map<String, Value>, indent: &str) -> Option<String> {
    let names: Vec<String> = match map.get("type")? {
        Value::String(t) => vec![t.clone()],
        Value::Array(ts) => ts.iter().filter_map(Value::as_str).map(str::to_owned).collect(),
        _ => return None,
    };
    let schema = Value::Object(map.clone());
    Some(union(
        names
            .iter()
            .map(|name| match name.as_str() {
                "string" => "string".to_owned(),
                "integer" | "number" => "number".to_owned(),
                "boolean" => "boolean".to_owned(),
                "null" => "null".to_owned(),
                "array" => {
                    let items = map.get("items").map_or_else(|| "unknown".to_owned(), |i| expr(i, indent));
                    format!("{}[]", paren_array(&items))
                }
                "object" => {
                    if map.get("properties").is_some() {
                        object_body(&schema, indent)
                    } else if let Some(additional) = map.get("additionalProperties") {
                        format!("{{ [key: string]: {} }}", expr(additional, indent))
                    } else {
                        "{ [key: string]: unknown }".to_owned()
                    }
                }
                _ => "unknown".to_owned(),
            })
            .collect(),
    ))
}

fn paren_array(item: &str) -> String {
    if item.contains(' ') && !item.starts_with('{') { format!("({item})") } else { item.to_owned() }
}

fn constants_file(schema: &Value, schema_hash: &str) -> String {
    let (min, max, version) = super::version_numbers();
    let mut out = String::from(HEADER);
    out.push_str("//\n// Protocol constants and the method catalogue.\n\n");
    let methods = schema.get("x-yaac-methods").and_then(Value::as_array).cloned().unwrap_or_default();
    let notifications = schema.get("x-yaac-notifications").and_then(Value::as_array).cloned().unwrap_or_default();

    // Imports for the request/notification maps.
    let mut imported: Vec<String> = Vec::new();
    let mut note = |s: &Value| {
        if let Some(r) = s.get("$ref").and_then(Value::as_str) {
            let name = ref_name(r);
            if !imported.contains(&name) {
                imported.push(name);
            }
        }
    };
    for m in &methods {
        note(&m["params"]);
        note(&m["result"]);
    }
    for n in &notifications {
        note(&n["params"]);
    }
    imported.sort();
    let _ = writeln!(out, "import type {{\n{}\n}} from \"./types.js\";\n", imported.iter().map(|n| format!("  {n},")).collect::<Vec<_>>().join("\n"));

    let _ = writeln!(
        out,
        "/** The protocol version this build speaks natively. Only the dialect module may read it. */\nexport const PROTOCOL_VERSION = {version} as const;\n/** Oldest protocol version this build supports (the last 3 besides its own). */\nexport const PROTOCOL_MIN = {min} as const;\n/** Newest protocol version this build supports. */\nexport const PROTOCOL_MAX = {max} as const;\n/** `schemaHash` for PROTOCOL_VERSION: hash of its frozen baseline, protocol/schema/v{version}.json. */\nexport const SCHEMA_HASH = {} as const;\n",
        serde_json::to_string(schema_hash).unwrap_or_default()
    );
    let frame = &schema["x-yaac-frame"];
    let _ = writeln!(
        out,
        "/** Hard limit on a frame's length field (kind byte + payload). */\nexport const MAX_FRAME_LEN = {} as const;\n/** Frame kind of a JSON message. */\nexport const FRAME_KIND_MESSAGE = {} as const;\n/** Frame kind of a data frame (`u32 LE stream` + bytes). */\nexport const FRAME_KIND_DATA = {} as const;\n/** Initial (and smallest) data chunk. */\nexport const DATA_CHUNK_MIN = {} as const;\n/** Largest data chunk. */\nexport const DATA_CHUNK_MAX = {} as const;\n",
        frame["maxFrameLen"], frame["kinds"]["message"], frame["kinds"]["data"], frame["dataChunkMin"], frame["dataChunkMax"]
    );

    // Method names.
    out.push_str("/** Every request method name. */\nexport const METHODS = {\n");
    for m in &methods {
        let name = m["name"].as_str().unwrap_or_default();
        let _ = writeln!(out, "  {}: {},", const_key(name), serde_json::to_string(name).unwrap_or_default());
    }
    out.push_str("} as const;\n\n/** Every notification method name. */\nexport const NOTIFICATIONS = {\n");
    for n in &notifications {
        let name = n["name"].as_str().unwrap_or_default();
        let _ = writeln!(out, "  {}: {},", const_key(name), serde_json::to_string(name).unwrap_or_default());
    }
    out.push_str("} as const;\n\n");
    out.push_str("/** A request method name. */\nexport type RequestMethod = (typeof METHODS)[keyof typeof METHODS];\n");
    out.push_str("/** A notification method name. */\nexport type NotificationMethod = (typeof NOTIFICATIONS)[keyof typeof NOTIFICATIONS];\n\n");

    out.push_str("/**\n * Methods valid before `initialize` succeeds (and after a failed negotiation): `initialize`\n * and the two frozen daemon-management calls.\n */\nexport const FROZEN_CORE_METHODS = [\n");
    for m in methods.iter().filter(|m| m["frozen"] == Value::Bool(true)) {
        let _ = writeln!(out, "  {},", m["name"]);
    }
    out.push_str("] as const;\n\n");

    // Error codes.
    let codes = schema["$defs"]["ErrorCode"]["anyOf"][0]["enum"].as_array().cloned().unwrap_or_default();
    out.push_str("/** Every error code this build knows. Codes are open: keep unknown ones. */\nexport const ERROR_CODES = {\n");
    for code in &codes {
        let code = code.as_str().unwrap_or_default();
        let _ = writeln!(out, "  {}: {},", code.to_ascii_uppercase(), serde_json::to_string(code).unwrap_or_default());
    }
    out.push_str("} as const;\n\n");

    // Request and notification maps.
    out.push_str("/** Params and result type of every request method. */\nexport interface RequestMap {\n");
    for m in &methods {
        let _ = writeln!(
            out,
            "  /** {} */\n  {}: {{ params: {}; result: {} }};",
            m["doc"].as_str().unwrap_or_default(),
            serde_json::to_string(&m["name"]).unwrap_or_default(),
            expr(&m["params"], ""),
            expr(&m["result"], "")
        );
    }
    out.push_str("}\n\n/** Params type of every notification. */\nexport interface NotificationMap {\n");
    for n in &notifications {
        let _ = writeln!(
            out,
            "  /** {} */\n  {}: {};",
            n["doc"].as_str().unwrap_or_default(),
            serde_json::to_string(&n["name"]).unwrap_or_default(),
            expr(&n["params"], "")
        );
    }
    out.push_str("}\n\n");

    // Static facts.
    out.push_str(
        "/** Who sends a method. */\nexport type Direction = \"hostToDaemon\" | \"daemonToHost\" | \"both\";\n/** Scheduling class: control always goes before bulk. */\nexport type TrafficClass = \"control\" | \"bulk\";\n\n/** Static facts about a request method. */\nexport interface MethodInfo {\n  direction: Direction;\n  /** Part of the frozen core. */\n  frozen: boolean;\n  /** Changes state: carries an `opId` and is never retried blindly. */\n  stateChanging: boolean;\n  requestClass: TrafficClass;\n  responseClass: TrafficClass;\n}\n\n/** Static facts about every request method. */\nexport const METHOD_INFO: { readonly [M in keyof RequestMap]: MethodInfo } = {\n",
    );
    for m in &methods {
        let _ = writeln!(
            out,
            "  {}: {{ direction: {}, frozen: {}, stateChanging: {}, requestClass: {}, responseClass: {} }},",
            m["name"], m["direction"], m["frozen"], m["stateChanging"], m["requestClass"], m["responseClass"]
        );
    }
    out.push_str("};\n\n/** Static facts about a notification. */\nexport interface NotificationInfo {\n  direction: Direction;\n  class: TrafficClass;\n}\n\n/** Static facts about every notification. */\nexport const NOTIFICATION_INFO: { readonly [N in keyof NotificationMap]: NotificationInfo } = {\n");
    for n in &notifications {
        let _ = writeln!(out, "  {}: {{ direction: {}, class: {} }},", n["name"], n["direction"], n["class"]);
    }
    out.push_str("};\n");
    out
}

fn const_key(method: &str) -> String {
    let mut key = String::new();
    let mut prev_lower = false;
    for c in method.chars() {
        if c == '/' {
            key.push('_');
            prev_lower = false;
        } else if c.is_ascii_uppercase() {
            if prev_lower {
                key.push('_');
            }
            key.push(c);
            prev_lower = false;
        } else {
            key.push(c.to_ascii_uppercase());
            prev_lower = c.is_ascii_lowercase();
        }
    }
    key
}
