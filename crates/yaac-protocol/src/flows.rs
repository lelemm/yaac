//! Flows that span several messages: start a thread, open a thread.
//!
//! A flow is an ordinary state machine that takes the session's selected [`Dialect`] and
//! calls its steps; it never looks at a version. Sans-I/O: the flow sends requests through
//! the [`ClientSession`] and is fed the responses whose ids it is waiting for.

use serde_json::Value;

use crate::dialect::Dialect;
use crate::methods::names;
use crate::rpc::{ErrorObject, RpcId};
use crate::session::{ClientSession, SessionError};
use crate::types::{
    AgentsPolicy, EffortId, InputPart, InstanceId, Item, JournalPosition, ModeId, ModelId, OpId, PageCursor, ProjectId, TargetPath,
    ThreadId, ThreadSubscribeResult, TurnId, UploadPresence,
};

// ── Start a thread ────────────────────────────────────────────────────────────────────────

/// Domain command: create a thread with its first message.
#[derive(Clone, Debug, PartialEq)]
pub struct StartThread {
    /// Operation id, generated by the client and kept with the draft.
    pub op_id: OpId,
    /// Provider instance.
    pub instance: InstanceId,
    /// Working directory (empty, or the project's folder, when `project` is given).
    pub cwd: TargetPath,
    /// The project to start in; the thread starts in the root of its folder.
    pub project: Option<ProjectId>,
    /// The chat's agents policy; `ask` when absent.
    pub agents: Option<AgentsPolicy>,
    /// Model.
    pub model: Option<ModelId>,
    /// Effort.
    pub effort: Option<EffortId>,
    /// Mode.
    pub mode: Option<ModeId>,
    /// Fast mode (D125).
    pub fast: Option<bool>,
    /// Ultrafast mode.
    pub ultrafast: Option<bool>,
    /// The first message.
    pub input: Vec<InputPart>,
}

/// Domain result of starting a thread.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Started {
    /// The new thread.
    pub thread_id: ThreadId,
    /// Its first turn.
    pub turn_id: TurnId,
}

/// Sends the request(s) that start a thread. Feed the response to
/// [`finish_start_thread`].
pub fn start_thread(session: &mut ClientSession, command: &StartThread) -> Result<RpcId, SessionError> {
    let dialect = ready(session, names::THREAD_START)?;
    let wire = dialect.build_start(command)?;
    session.request_wire(names::THREAD_START, wire)
}

/// Decodes the response to [`start_thread`].
pub fn finish_start_thread(session: &ClientSession, wire: Value) -> Result<Started, SessionError> {
    Ok(ready(session, names::THREAD_START)?.decode_started(wire)?)
}

// ── Open a thread ─────────────────────────────────────────────────────────────────────────

/// Domain command: open a thread — subscribe, and read a snapshot if the journal cannot be
/// replayed from the client's position.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct OpenThread {
    /// The thread.
    pub thread_id: ThreadId,
    /// The client's durable position, if it has one.
    pub after: Option<JournalPosition>,
    /// Page size bound for snapshot reads, in bytes.
    pub page_bytes: Option<u64>,
}

/// A snapshot page read after a reset.
#[derive(Clone, Debug, PartialEq)]
pub struct Snapshot {
    /// Items, newest first.
    pub items: Vec<Item>,
    /// The position the snapshot is valid at: apply only events strictly after it.
    pub position: JournalPosition,
    /// Cursor for older pages (bound to this snapshot), if any.
    pub cursor: Option<PageCursor>,
    /// Attachment presence for these items.
    pub uploads: Vec<UploadPresence>,
}

/// The result of opening a thread.
#[derive(Clone, Debug, PartialEq)]
pub struct Opened {
    /// The subscription: mode, control, effective capabilities.
    pub subscribed: ThreadSubscribeResult,
    /// The first snapshot page, after a reset. `None` after a replay: the journal events that
    /// follow bring the client up to date.
    pub snapshot: Option<Snapshot>,
}

/// Progress of a flow.
#[derive(Clone, Debug, PartialEq)]
pub enum FlowStep<T> {
    /// Waiting for the response to the returned request id.
    Waiting(RpcId),
    /// Finished.
    Done(T),
}

/// A flow failed.
#[derive(Debug, thiserror::Error)]
pub enum FlowError {
    /// The daemon answered with an error.
    #[error(transparent)]
    Remote(#[from] ErrorObject),
    /// A local session or dialect error.
    #[error(transparent)]
    Session(#[from] SessionError),
    /// The flow was fed after it finished.
    #[error("the flow has already finished")]
    Finished,
}

#[derive(Debug)]
enum OpenState {
    Subscribing,
    Reading(Box<ThreadSubscribeResult>),
    Done,
}

/// The open-thread flow. Start it, then feed it the response for [`OpenThreadFlow::waiting`]
/// until it returns [`FlowStep::Done`].
#[derive(Debug)]
pub struct OpenThreadFlow {
    command: OpenThread,
    waiting: Option<RpcId>,
    state: OpenState,
}

impl OpenThreadFlow {
    /// Sends `thread/subscribe`.
    pub fn start(session: &mut ClientSession, command: OpenThread) -> Result<Self, SessionError> {
        let dialect = ready(session, names::THREAD_SUBSCRIBE)?;
        let wire = dialect.build_subscribe(&command)?;
        let id = session.request_wire(names::THREAD_SUBSCRIBE, wire)?;
        Ok(Self { command, waiting: Some(id), state: OpenState::Subscribing })
    }

    /// The request id whose response this flow needs next.
    pub fn waiting(&self) -> Option<&RpcId> {
        self.waiting.as_ref()
    }

    /// Feeds the response (wire result or error) to the request the flow is waiting for.
    pub fn on_response(
        &mut self,
        session: &mut ClientSession,
        outcome: Result<Value, ErrorObject>,
    ) -> Result<FlowStep<Opened>, FlowError> {
        let wire = outcome?;
        let state = std::mem::replace(&mut self.state, OpenState::Done);
        match state {
            OpenState::Subscribing => {
                let dialect = ready(session, names::THREAD_SUBSCRIBE)?;
                let subscribed = dialect.decode_subscribed(wire).map_err(SessionError::from)?;
                match dialect.read_first_page(&self.command, &subscribed).map_err(SessionError::from)? {
                    None => {
                        self.waiting = None;
                        Ok(FlowStep::Done(Opened { subscribed, snapshot: None }))
                    }
                    Some(read) => {
                        let id = session.request_wire(names::THREAD_READ, read)?;
                        self.waiting = Some(id.clone());
                        self.state = OpenState::Reading(Box::new(subscribed));
                        Ok(FlowStep::Waiting(id))
                    }
                }
            }
            OpenState::Reading(subscribed) => {
                let dialect = ready(session, names::THREAD_READ)?;
                let page = dialect.decode_page(wire).map_err(SessionError::from)?;
                self.waiting = None;
                Ok(FlowStep::Done(Opened {
                    subscribed: *subscribed,
                    snapshot: Some(Snapshot {
                        items: page.items,
                        position: page.position,
                        cursor: page.cursor,
                        uploads: page.uploads,
                    }),
                }))
            }
            OpenState::Done => Err(FlowError::Finished),
        }
    }
}

/// Requests the next (older) page of a snapshot. Decode the response with [`finish_page`].
pub fn read_older_page(
    session: &mut ClientSession,
    command: &OpenThread,
    cursor: &PageCursor,
) -> Result<RpcId, SessionError> {
    let dialect = ready(session, names::THREAD_READ)?;
    let wire = dialect.read_next_page(command, cursor)?;
    session.request_wire(names::THREAD_READ, wire)
}

/// Decodes a `thread/read` response into a snapshot page.
pub fn finish_page(session: &ClientSession, wire: Value) -> Result<Snapshot, SessionError> {
    let page = ready(session, names::THREAD_READ)?.decode_page(wire)?;
    Ok(Snapshot { items: page.items, position: page.position, cursor: page.cursor, uploads: page.uploads })
}

fn ready(session: &ClientSession, method: &'static str) -> Result<&'static Dialect, SessionError> {
    session.dialect().ok_or(SessionError::NotReady(method))
}
